const priceSearchButton = document.querySelector("#priceSearchButton");

const priceResultsCount = document.querySelector("#priceResultsCount");

const noPriceResults = document.querySelector("#noPriceResults");

const priceFilterButtons = document.querySelectorAll(".price-filter");

/* =========================================================
   CURRENT FILTER
   ========================================================= */

let currentPriceCategory = "all";

/* =========================================================
   FORMAT PRICE
   ========================================================= */

function formatPrice(price) {
  if (typeof price === "number") {
    return "K" + price.toLocaleString();
  }

  return "K" + price;
}

/* =========================================================
   DISPLAY PRICE PRODUCTS
   ========================================================= */

function displayPriceProducts() {
  /* Make sure the price list exists on the page */

  if (!priceListContainer) {
    return;
  }

  /* Get search term */

  const searchTerm = priceSearchInput
    ? priceSearchInput.value.trim().toLowerCase()
    : "";

  /* Filter products */

  const filteredProducts = priceListProducts.filter(function (product) {
    /* Category filter */

    const matchesCategory =
      currentPriceCategory === "all" ||
      product.category === currentPriceCategory;

    /* Search filter */

    const searchableText = (
      product.name +
      " " +
      product.description +
      " " +
      product.publisher
    ).toLowerCase();

    const matchesSearch = searchableText.includes(searchTerm);

    return matchesCategory && matchesSearch;
  });

  /* Clear existing products */

  priceListContainer.innerHTML = "";

  /* Update number of results */

  if (priceResultsCount) {
    priceResultsCount.textContent =
      filteredProducts.length +
      " product" +
      (filteredProducts.length === 1 ? "" : "s") +
      " found";
  }

  /* Show no results message */

  if (filteredProducts.length === 0) {
    if (noPriceResults) {
      noPriceResults.style.display = "block";
    }

    return;
  }

  /* Hide no results message */

  if (noPriceResults) {
    noPriceResults.style.display = "none";
  }

  /* Create product cards */

  filteredProducts.forEach(function (product) {
    const card = document.createElement("article");

    card.classList.add("price-card");

    card.innerHTML = `

            <div class="price-card-top">

                <span class="price-category">
                    ${getCategoryName(product.category)}
                </span>

            </div>


            <div class="price-card-content">

                <h3>
                    ${product.name}
                </h3>

                <p class="price-description">
                    ${product.description}
                </p>

                <p class="price-publisher">
                    <strong>Publisher:</strong>
                    ${product.publisher}
                </p>

            </div>


            <div class="price-card-bottom">

                <span class="price-label">
                    Price
                </span>

                <span class="product-price">
                    ${formatPrice(product.price)}
                </span>

            </div>

        `;

    priceListContainer.appendChild(card);
  });
}

/* =========================================================
   CATEGORY NAME
   ========================================================= */

function getCategoryName(category) {
  const categoryNames = {
    secondary: "Secondary Books",

    "made-simple": "Made Simple",

    literature: "Literature",

    dictionaries: "Dictionaries",

    "secondary-teacher": "Secondary Teacher's Guide",

    "primary-teacher": "Primary Teacher's Guide",
  };

  return categoryNames[category] || "Books";
}

