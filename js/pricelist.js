if (priceSearchButton) {
  priceSearchButton.addEventListener("click", function () {
    displayPriceProducts();
  });
}

/* =========================================================
   SEARCH WHILE TYPING
   ========================================================= */

if (priceSearchInput) {
  priceSearchInput.addEventListener("input", function () {
    displayPriceProducts();
  });

  /* Search using ENTER */

  priceSearchInput.addEventListener("keydown", function (event) {
    if (event.key === "Enter") {
      displayPriceProducts();
    }
  });
}

/* =========================================================
   CATEGORY FILTERS
   ========================================================= */

priceFilterButtons.forEach(function (button) {
  button.addEventListener("click", function () {
    /* Remove active class */

    priceFilterButtons.forEach(function (filterButton) {
      filterButton.classList.remove("active");
    });

    /* Activate clicked button */

    button.classList.add("active");

    /* Change category */

    currentPriceCategory = button.dataset.category;

    /* Display products */

    displayPriceProducts();
  });
});

